// Note grid conventions per 16th-note step:
// > 0  = MIDI pitch trigger
//  -1  = sustain / hold previous note (creates singing Contra: Hard Corps brass & guitar phrases!)
//   0  = rest
//
// Drum grid tokens per 16th-note step:
// K = Punchy Genesis Kick, S = 12-bit DAC Snare, g = Tight Ghost Snare,
// H = Closed Hat, O = Open Hat, C = Crash Cymbal,
// T = High/Mid Sega Tom, t = Low Floor Tom, M = Metallic FM Clang / Cowbell
type LeadVoice = 'fm_guitar' | 'fm_brass' | 'fm_synth_lead';
type BassVoice = 'fm_pick' | 'fm_slap' | 'fm_sub';

interface TrackSection {
  bass: number[]; // 32 steps (2 bars)
  lead: number[]; // 32 steps (2 bars, supports -1 sustain)
  arp: number[]; // 32 steps (SN76489 PSG counter-harmony / baroque arpeggio / rhythm fifths)
  hit: number[]; // 32 steps (root MIDI note for Sega Genesis Orchestra Hit / power-chord crash, or 0)
  drums: string[]; // 32 steps
}

interface HardCorpsTrack {
  bpm: number;
  leadVoice: LeadVoice;
  bassVoice: BassVoice;
  drive: number;
  muffled?: boolean;
  sections: [TrackSection, TrackSection, TrackSection, TrackSection]; // Full 8-bar (128-step) composition!
}

interface SynthwaveTrack {
  bpm: number;
  isSynthwave: true;
  drive: number;
  padChords: number[][];
  bassA: number[];
  bassB: number[];
  leadA: number[];
  leadB: number[];
  stab: number[];
  drumsA: string[];
  drumsB: string[];
}

type TrackPattern = HardCorpsTrack | SynthwaveTrack;

